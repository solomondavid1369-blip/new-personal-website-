#!/usr/bin/env bash
# Turns the hero clip into WebP image sequences for the scroll-driven canvas.
#
#   ./scripts/extract-frames.sh
#
# Reads  public/hero/source-desktop.mp4 (required) and public/hero/source-mobile.mp4 (optional).
# Writes public/hero/desktop/0001.webp... and public/hero/mobile/0001.webp...
# and content/hero-frames.ts with the frame counts and sizes the player needs.
#
# If there is no mobile clip, the mobile set is a 9:16 slice cropped from the
# desktop clip at MOBILE_CROP_X (positioned on David, not the centre).
# Frames are never upscaled beyond the source resolution.
set -euo pipefail
cd "$(dirname "$0")/.."

DESKTOP_SRC=public/hero/source-desktop.mp4
MOBILE_SRC=public/hero/source-mobile.mp4
DESKTOP_DIR=public/hero/desktop
MOBILE_DIR=public/hero/mobile

DESKTOP_WIDTH=${DESKTOP_WIDTH:-1600}
MOBILE_WIDTH=${MOBILE_WIDTH:-720}
DESKTOP_FRAMES=${DESKTOP_FRAMES:-110}
MOBILE_FRAMES=${MOBILE_FRAMES:-72}
DESKTOP_QUALITY=${DESKTOP_QUALITY:-88}
MOBILE_QUALITY=${MOBILE_QUALITY:-70}
MOBILE_CROP_X=${MOBILE_CROP_X:-638}

DESKTOP_BUDGET_KB=5000
MOBILE_BUDGET_KB=2500

[[ -f $DESKTOP_SRC ]] || { echo "Missing $DESKTOP_SRC"; exit 1; }

probe() { ffprobe -v error -select_streams v:0 -show_entries "$1" -of csv=p=0 "$2"; }

# extract <src> <out_dir> <target_frames> <max_width> <quality> [crop_filter]
extract() {
  local src=$1 out=$2 frames=$3 max_w=$4 quality=$5 crop=${6:-}
  local duration src_w fps chain
  duration=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$src")
  src_w=$(probe stream=width "$src")
  [[ -n $crop ]] && src_w=$(sed -E 's/crop=([0-9]+):.*/\1/' <<<"$crop")
  local w=$(( src_w < max_w ? src_w : max_w ))
  fps=$(awk -v n="$frames" -v d="$duration" 'BEGIN { printf "%.4f", n / d }')

  chain="fps=$fps"
  [[ -n $crop ]] && chain="$chain,$crop"
  chain="$chain,scale=$w:-2:flags=lanczos"

  rm -rf "$out" && mkdir -p "$out"
  ffmpeg -v error -i "$src" -vf "$chain" -c:v libwebp -quality "$quality" \
    -compression_level 6 -preset photo "$out/%04d.webp"
}

extract "$DESKTOP_SRC" "$DESKTOP_DIR" "$DESKTOP_FRAMES" "$DESKTOP_WIDTH" "$DESKTOP_QUALITY"

if [[ -f $MOBILE_SRC ]]; then
  extract "$MOBILE_SRC" "$MOBILE_DIR" "$MOBILE_FRAMES" "$MOBILE_WIDTH" "$MOBILE_QUALITY"
else
  src_h=$(probe stream=height "$DESKTOP_SRC")
  crop_w=$(( src_h * 9 / 16 / 2 * 2 ))
  extract "$DESKTOP_SRC" "$MOBILE_DIR" "$MOBILE_FRAMES" "$MOBILE_WIDTH" "$MOBILE_QUALITY" \
    "crop=$crop_w:$src_h:$MOBILE_CROP_X:0"
fi

# Frame counts and pixel sizes for the player.
set_info() {
  local dir=$1 count dims
  count=$(find "$dir" -name '*.webp' | wc -l | tr -d ' ')
  dims=$(probe stream=width,height "$dir/0001.webp")
  echo "{ count: $count, width: ${dims%,*}, height: ${dims#*,} }"
}
cat > content/hero-frames.ts <<TS
// Generated by scripts/extract-frames.sh. Do not edit by hand.
export const heroFrames = {
  desktop: $(set_info "$DESKTOP_DIR"),
  mobile: $(set_info "$MOBILE_DIR"),
} as const;
TS

report() {
  local dir=$1 budget=$2 kb count
  kb=$(du -sk "$dir" | cut -f1)
  count=$(find "$dir" -name '*.webp' | wc -l | tr -d ' ')
  local status="OK"
  (( kb > budget )) && status="OVER BUDGET (${budget}KB): lower the quality or the frame count"
  printf '%-8s %3s frames  %5s KB  %s\n' "$(basename "$dir")" "$count" "$kb" "$status"
}
echo
report "$DESKTOP_DIR" "$DESKTOP_BUDGET_KB"
report "$MOBILE_DIR" "$MOBILE_BUDGET_KB"
